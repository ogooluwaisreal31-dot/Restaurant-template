(() => {
  const base = JSON.parse(JSON.stringify(window.RESTAURANT_CONFIG || {}));
  const form = document.getElementById('admin-form');
  const menuRoot = document.getElementById('menu-items');
  const status = document.getElementById('status');
  const fieldNames = ['name','tagline','heroTitle','heroDescription','phoneDisplay','phoneDial','whatsapp','currency','address','openingHours','mapQuery','aboutTitle','aboutText','primaryColor','accentColor'];
  const escapeHtml = (s) => String(s ?? '').replace(/[&<>"']/g, ch => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[ch]));
  function addMenuItem(item = {}) {
    const box = document.createElement('div'); box.className = 'menu-item';
    box.innerHTML = `<div class="menu-item-top"><strong>Menu item</strong><button type="button" class="remove-menu">Remove</button></div><div class="fields">
      <label>Name<input data-key="name" required value="${escapeHtml(item.name)}"></label>
      <label>Price (number)<input data-key="price" type="number" min="0" step="1" value="${escapeHtml(item.price ?? 0)}"></label>
      <label class="wide">Description<textarea data-key="description" rows="2">${escapeHtml(item.description)}</textarea></label>
      <label class="wide">Image URL<input data-key="image" type="url" value="${escapeHtml(item.image)}" placeholder="https://..."></label>
    </div>`;
    box.querySelector('.remove-menu').addEventListener('click', () => box.remove());
    menuRoot.append(box);
  }
  function readConfig() {
    const c = {...base};
    for (const key of fieldNames) { const el = form.elements.namedItem(key); if (el) c[key] = el.value.trim(); }
    c.menu = [...menuRoot.querySelectorAll('.menu-item')].map(box => {
      const get = key => box.querySelector(`[data-key="${key}"]`).value.trim();
      return {name:get('name'), price:Number(get('price') || 0), description:get('description'), image:get('image')};
    }).filter(item => item.name);
    c.gallery = (form.elements.galleryText.value || '').split(/\r?\n/).map(x=>x.trim()).filter(Boolean);
    return c;
  }
  function populate(c) {
    for (const key of fieldNames) { const el = form.elements.namedItem(key); if (el && c[key] != null) el.value = c[key]; }
    form.elements.galleryText.value = (c.gallery || []).join('\n');
    menuRoot.replaceChildren(); (c.menu || []).forEach(addMenuItem);
    document.getElementById('dash-brand').textContent = `${c.name || 'Restaurant'} Admin`;
  }
  function activeConfig() {
    try { const saved = localStorage.getItem('restaurantAdminPreview'); return saved ? JSON.parse(saved) : base; } catch { return base; }
  }
  form.addEventListener('submit', event => {
    event.preventDefault();
    const c = readConfig();
    try { localStorage.setItem('restaurantAdminPreview', JSON.stringify(c)); status.textContent = 'Preview saved in this browser. Open the website in this same browser to see the local preview.'; }
    catch { status.textContent = 'Could not save locally. Download config.js to keep your changes.'; }
    document.getElementById('dash-brand').textContent = `${c.name || 'Restaurant'} Admin`;
  });
  document.getElementById('add-menu').addEventListener('click', () => addMenuItem({name:'New dish',price:0,description:'',image:''}));
  document.getElementById('download-config').addEventListener('click', () => {
    const c = readConfig();
    const contents = '/* Generated by the Restaurant Admin Dashboard. Review all details before publishing. */\nwindow.RESTAURANT_CONFIG = ' + JSON.stringify(c, null, 2) + ';\n';
    const blob = new Blob([contents], {type:'text/javascript;charset=utf-8'}); const url = URL.createObjectURL(blob);
    const a = document.createElement('a'); a.href = url; a.download = 'config.js'; document.body.append(a); a.click(); a.remove(); URL.revokeObjectURL(url);
    status.textContent = 'Downloaded config.js. Upload it to your GitHub repository, replace the old file, and commit the change to publish.';
  });
  document.getElementById('reset-config').addEventListener('click', () => {
    localStorage.removeItem('restaurantAdminPreview'); populate(base); status.textContent = 'Local preview cleared. The original config.js values are loaded.';
  });
  populate(activeConfig());
})();
